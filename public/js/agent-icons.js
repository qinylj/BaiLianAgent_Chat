/**
 * 智能体图标（内联 SVG）。
 *
 * 为什么不用 emoji：emoji 由系统字体渲染，Windows / macOS / Android 三套字形完全不同，
 * 尺寸和基线也不受控（历史上 💧 这种 ZWJ 组合 emoji 还曾渲染成两个图标）；而且它只有固定配色，
 * 没法跟智能体自己的 accent 色、也没法跟深色 / 浅色 / 驾驶舱三套主题联动。
 *
 * 设计语言（6 个图标共用，保证看起来是一套）：
 *  - 24×24 网格，图形收在 16×16 安全区内（四周留 4px，小尺寸下才不挤）
 *  - 1.7px 描边、圆头圆角、只描边不填充（fill:none）
 *  - 单色：描边用 currentColor，颜色由外层容器的 color 决定，主题切换零成本
 *  - 「**外轮廓 = 动作，内部符号 = 领域**」：
 *      星芒   = 通用咨询        （AI 通用符号，居中单形、无内部元素）
 *      盾牌   = 处置（×2）      ┐ 防汛 = 波浪 / 水污染 = 水滴
 *      文档   = 评价复盘（×2）  ┘ 内部符号与同领域的「处置」保持一致
 *      放大镜 = 溯源            （镜内水滴）
 *    于是「防汛」这两个图标里都有波浪或折线，「水污染」这三个里都有水滴 ——
 *    侧栏里一眼能看出哪几个是同一领域的，动作则靠外轮廓（盾 / 文档 / 放大镜）分辨。
 *
 * 另有一个 `user` 不是智能体图标，而是**用户自己的头像**（消息列表左侧那颗）：
 * 它只要和这 6 个长得像一家人、并且一眼看出「这是人，不是 AI」。中性人形（圆头 + 半圆肩）
 * 是唯一零歧义的形状 —— 试过平肩带竖线 / 收窄肩 / 两侧留缺口肩几种，26px 下都退化成
 * 不好分辨的小疙瘩，半圆肩在最小尺寸下仍然读得出「头 + 肩」。
 *
 * 为什么「长寿机关大脑」用星芒而不是一颗具象的大脑：在 26–34px 的实际渲染尺寸下试过
 * 十余版脑形（双圆相交 / 单圆加中缝 / 双半圆拼合 / 带沟回的椭圆…），一律读成「两个环」「地球仪」
 * 「洋葱」，而且频繁撞形 —— 灯泡缩到 26px 像水滴（撞水污染）、左右双瓣像盾牌（撞防汛）。
 * 结论：这个尺寸容不下具象器官，于是回到 AI 产品通用的星芒符号，语义（智能）准确、
 * 形状与其余五个零冲突。**要换成具象脑，只改下面这一行路径即可。**
 *
 * 想调图标只改这个文件：路径即设计稿，改完刷新页面即可。
 */

const S = (inner) => inner.trim().replace(/\s+/g, ' ');

/* 盾牌外轮廓（防汛处置 / 水污染处置共用），19×17 */
const SHIELD = 'M12 3.4 5.5 6v6c0 4 2.7 7.2 6.5 8.2 3.8-1 6.5-4.2 6.5-8.2V6z';
/* 文档外轮廓（两个复盘共用）：右上折角，11.3×17.4 */
const DOC = 'M6.9 3.6h6.3l4.9 4.9v11a1 1 0 0 1-1 1H6.9a1 1 0 0 1-1-1v-15a1 1 0 0 1 1-1z';
const DOC_FOLD = 'M13.2 3.6v4.9h4.9';
/* 一滴水：宽 5、高约 6.8，水滴尖在 (cx, cy) */
const dropAt = (cx, cy) =>
  `M${cx} ${cy}c1.7 2 2.5 3.3 2.5 4.3a2.5 2.5 0 0 1-5 0c0-1 .8-2.3 2.5-4.3z`;
/* 一道浪：宽 6、振幅 1.1，左端在 (x, y) */
const waveAt = (x, y) => `M${x} ${y}c1-1.1 2-1.1 3 0s2 1.1 3 0`;

export const AGENT_ICON_PATHS = {
  /* 长寿机关大脑（通用咨询）：四角星芒 —— 居中单形，缩到 26px 也不会糊。
     控制点 (13,11) 很靠近中心，靠二次贝塞尔把「腰」收到尖端的 45% —— 给大了就退化成菱形。 */
  sparkle: S(`
    <path d="M12 4.6Q13 11 19.4 12 13 13 12 19.4 11 13 4.6 12 11 11 12 4.6Z" />
  `),

  /* 防汛事件处置建议：盾 + 两道水位浪 */
  flood: S(`
    <path d="${SHIELD}" />
    <path d="${waveAt(9, 11.9)}" />
    <path d="${waveAt(9, 15)}" />
  `),

  /* 防汛事件评价复盘：文档 + 折线（复盘 = 拿水位数据说话） */
  floodReport: S(`
    <path d="${DOC}" />
    <path d="${DOC_FOLD}" />
    <path d="M9.2 16.4l2.2-2.5 1.7 1.5 2.7-3.1" />
  `),

  /* 水污染事件处置建议：盾 + 一滴水 */
  water: S(`
    <path d="${SHIELD}" />
    <path d="${dropAt(12, 9.2)}" />
  `),

  /* 水污染事件辅助溯源：放大镜 + 镜内水滴（溯源 = 拿着数据往回找） */
  trace: S(`
    <circle cx="10.4" cy="10.4" r="6.2" />
    <path d="M15.1 15.1 20.2 20.2" />
    <path d="${dropAt(10.4, 7.6)}" />
  `),

  /* 水污染事件评价复盘：文档 + 一滴水（与「水污染处置」的领域符号一致） */
  waterReport: S(`
    <path d="${DOC}" />
    <path d="${DOC_FOLD}" />
    <path d="${dropAt(12, 10.4)}" />
  `),

  /* 大模型（config/models.json 里的条目）：芯片 —— 圆角方框 + 八根引脚 + 中心核。
     为什么不用「大脑」具象形：这个渲染尺寸（26–34px）容不下具象器官，试过十余版脑形，
     一律读成「两个环」「地球仪」「洋葱」（详见文件头对 sparkle 的那段结论），
     所以沿用 AI 硬件的通用符号。它与另外七个形状零冲突：这是唯一以「方」为主形的
     （盾牌上平下尖、文档带右上折角、放大镜与头像都是圆、sparkle 是星芒）。 */
  chip: S(`
    <rect x="6.6" y="6.6" width="10.8" height="10.8" rx="2.4" />
    <path d="M4.2 10.2h2.4" />
    <path d="M4.2 13.8h2.4" />
    <path d="M17.4 10.2h2.4" />
    <path d="M17.4 13.8h2.4" />
    <path d="M10.2 4.2v2.4" />
    <path d="M13.8 4.2v2.4" />
    <path d="M10.2 17.4v2.4" />
    <path d="M13.8 17.4v2.4" />
    <circle cx="12" cy="12" r="2.2" />
  `),

  /* 用户自己的头像：圆头 + 半圆肩（**不是智能体图标**，见文件头说明）。
     放在这个表里只是为了调用方统一走 agentIconSvg()，不必另维护一个渲染函数。
     肩用 A 弧正好半圆（弦 12.8 = 直径 12.8），两端切线竖直，缩到 16px 也不会塌成一条线。 */
  user: S(`
    <circle cx="12" cy="8.8" r="3.5" />
    <path d="M5.6 20.2a6.4 6.4 0 0 1 12.8 0" />
  `),
};

/** 兜底图标（配置里 icon 写错 / 未配时用）：圆角方框 + 双点，比什么都不画安全 */
const FALLBACK = S(`
  <rect x="4.6" y="4.6" width="14.8" height="14.8" rx="4" />
  <path d="M9.4 11.6v.9" />
  <path d="M14.6 11.6v.9" />
`);

/**
 * 生成智能体图标的 SVG 字符串。
 * @param {string} iconId AGENT_ICON_PATHS 的键（来自 agents.json 的 icon 字段）
 * @param {string} className 附加类名（一般传 'agent-icon'，尺寸由 CSS 控制）
 */
export function agentIconSvg(iconId, className = 'agent-icon') {
  const inner = AGENT_ICON_PATHS[iconId] || FALLBACK;
  return (
    `<svg class="${className}" viewBox="0 0 24 24" fill="none" stroke="currentColor"` +
    ' stroke-width="1.7" stroke-linecap="round" stroke-linejoin="round"' +
    ' aria-hidden="true" focusable="false">' +
    `<g>${inner}</g></svg>`
  );
}
